//! Emit Rust-oracle Connect envelope vectors consumed by the C++ SDK codec tests.

use std::{
    env,
    fs::{self, File},
    io::{self, Write as _},
    path::{Path, PathBuf},
};

const MANIFEST: &str = "Rust-oracle Connect envelope vectors for the C++ SDK pure codec.\n\
\n\
Generated by `cargo run -p crabka-sdk-conformance --bin emit_cpp_codec_oracle_vectors -- sdks/cpp/test/vectors`.\n\
The generator is the checked-in Rust oracle seam for Connect envelope framing: one flag byte,\n\
a 32-bit big-endian payload length, and exact payload bytes. EndStream uses the Connect\n\
end-stream flag (0x02), not the gRPC-Web trailer flag (0x80). C++ tests must consume\n\
these bytes rather than reconstructing expected frames inline.\n\
\n\
message_payload_pay.hex: single uncompressed message frame with payload `pay`\n\
compressed_payload_pay.hex: single compressed-bit message frame with payload `pay`\n\
multi_frame_stream.hex: two message frames, `one` then `two`\n\
partial_header.hex: truncated three-byte prefix for NeedMore coverage\n\
endstream_clean.hex: clean Connect EndStream frame with empty payload\n\
endstream_not_found.hex: Connect EndStream frame carrying `{\"error\":{\"code\":\"not_found\",\"message\":\"missing\"}}`\n";

struct OracleVector {
    name: &'static str,
    bytes: Vec<u8>,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output_dir = parse_output_dir(env::args_os().skip(1))?;
    emit_vectors(&output_dir)?;
    Ok(())
}

fn parse_output_dir(mut args: impl Iterator<Item = std::ffi::OsString>) -> io::Result<PathBuf> {
    let Some(output_dir) = args.next() else {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "usage: emit_cpp_codec_oracle_vectors <output-dir>",
        ));
    };
    if args.next().is_some() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "usage: emit_cpp_codec_oracle_vectors <output-dir>",
        ));
    }
    Ok(output_dir.into())
}

fn emit_vectors(output_dir: &Path) -> io::Result<()> {
    fs::create_dir_all(output_dir)?;
    for vector in oracle_vectors() {
        write_hex_file(&output_dir.join(vector.name), &vector.bytes)?;
    }
    fs::write(output_dir.join("manifest.txt"), MANIFEST)
}

fn oracle_vectors() -> Vec<OracleVector> {
    vec![
        OracleVector {
            name: "message_payload_pay.hex",
            bytes: encode_frame(0x00, b"pay"),
        },
        OracleVector {
            name: "compressed_payload_pay.hex",
            bytes: encode_frame(0x01, b"pay"),
        },
        OracleVector {
            name: "multi_frame_stream.hex",
            bytes: [encode_frame(0x00, b"one"), encode_frame(0x00, b"two")].concat(),
        },
        OracleVector {
            name: "partial_header.hex",
            bytes: vec![0x00, 0x00, 0x00],
        },
        OracleVector {
            name: "endstream_clean.hex",
            bytes: encode_frame(0x02, b""),
        },
        OracleVector {
            name: "endstream_not_found.hex",
            bytes: encode_frame(
                0x02,
                br#"{"error":{"code":"not_found","message":"missing"}}"#,
            ),
        },
    ]
}

fn encode_frame(flags: u8, payload: &[u8]) -> Vec<u8> {
    let size = u32::try_from(payload.len()).expect("oracle payload length fits in u32");
    let mut frame = Vec::with_capacity(payload.len() + 5);
    frame.push(flags);
    frame.extend_from_slice(&size.to_be_bytes());
    frame.extend_from_slice(payload);
    frame
}

fn write_hex_file(path: &Path, bytes: &[u8]) -> io::Result<()> {
    let mut file = File::create(path)?;
    for byte in bytes {
        write!(file, "{byte:02x}")?;
    }
    writeln!(file)
}
