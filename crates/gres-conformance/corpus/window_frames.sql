-- Q2: window frames — ROWS / RANGE / GROUPS, every bound spelling, the
-- single-bound and BETWEEN forms, EXCLUDE, RANGE offsets over numeric and
-- temporal ordering columns, and the frame errors. Diffed against PostgreSQL 18.4.
--
-- Every query carries a total ORDER BY (see window_functions.sql).
CREATE TABLE frm (g int4, v int4);
INSERT INTO frm VALUES (1, 10), (1, 20), (2, 30), (2, 30), (3, 40), (3, NULL);

-- the default frame is RANGE UNBOUNDED PRECEDING AND CURRENT ROW: peers share it
SELECT g, v, sum(v) OVER (ORDER BY g) FROM frm ORDER BY g, v;
SELECT g, v, sum(v) OVER (ORDER BY g, v) FROM frm ORDER BY g, v NULLS LAST;
-- with no ORDER BY the frame is the whole partition
SELECT g, v, sum(v) OVER (PARTITION BY g) FROM frm ORDER BY g, v NULLS LAST;

-- ROWS: the BETWEEN form, every bound spelling
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN 2 PRECEDING AND 1 PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN 1 FOLLOWING AND 2 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g, v ROWS BETWEEN CURRENT ROW AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
-- the single-bound form expands to BETWEEN <bound> AND CURRENT ROW
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS UNBOUNDED PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS 1 PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
-- an out-of-range ROWS frame is empty, not an error
SELECT g, v, count(*) OVER (ORDER BY g, v ROWS BETWEEN 9 FOLLOWING AND 10 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g, v ROWS BETWEEN 9 FOLLOWING AND 10 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
-- ROWS offsets take a bigint: an unknown literal and a rounded numeric both work
SELECT g, v, count(*) OVER (ORDER BY g, v ROWS '1' PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g, v ROWS 1.5 PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g, v ROWS BETWEEN 1 + 1 PRECEDING AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
-- ROWS is per row, so it splits peer groups where RANGE does not
SELECT g, v, count(*) OVER (PARTITION BY g ORDER BY v ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;

-- RANGE without an offset is peer-based
SELECT g, v, count(*) OVER (ORDER BY g RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g RANGE BETWEEN CURRENT ROW AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;

-- RANGE with an offset uses the ordering column's arithmetic
SELECT v, sum(v) OVER (ORDER BY v RANGE BETWEEN 10 PRECEDING AND 10 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v RANGE BETWEEN 10 PRECEDING AND CURRENT ROW) FROM frm ORDER BY v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v RANGE BETWEEN CURRENT ROW AND 10 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN UNBOUNDED PRECEDING AND 10 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN 10 PRECEDING AND UNBOUNDED FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v RANGE 10 PRECEDING) FROM frm ORDER BY v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v RANGE BETWEEN 20 PRECEDING AND 10 PRECEDING) FROM frm ORDER BY v NULLS LAST;
-- a DESC ordering mirrors both directions
SELECT v, sum(v) OVER (ORDER BY v DESC RANGE BETWEEN 10 PRECEDING AND 10 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v DESC RANGE BETWEEN 10 PRECEDING AND CURRENT ROW) FROM frm ORDER BY v NULLS LAST;
-- a zero offset is the peer group
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN 0 PRECEDING AND 0 FOLLOWING) FROM frm ORDER BY v NULLS LAST;

-- GROUPS counts whole peer groups
SELECT g, v, count(*) OVER (ORDER BY g GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g GROUPS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g GROUPS 1 PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g GROUPS BETWEEN 1 FOLLOWING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g GROUPS BETWEEN 1 PRECEDING AND 0 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER (ORDER BY g GROUPS BETWEEN 5 PRECEDING AND 5 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;

-- EXCLUDE, over a frame that spans the whole partition so the effect is exact
SELECT g, v, sum(v) OVER w FROM frm WINDOW w AS (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE NO OTHERS) ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER w FROM frm WINDOW w AS (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE CURRENT ROW) ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER w FROM frm WINDOW w AS (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE GROUP) ORDER BY g, v NULLS LAST;
SELECT g, v, sum(v) OVER w FROM frm WINDOW w AS (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE TIES) ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (PARTITION BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE GROUP) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE GROUP) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, v, count(*) OVER (ORDER BY g RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE TIES) FROM frm ORDER BY g, v NULLS LAST;

-- the frame is what first_value / last_value / nth_value read
SELECT g, v, first_value(v) OVER w, last_value(v) OVER w, nth_value(v, 2) OVER w FROM frm WINDOW w AS (ORDER BY g, v ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) ORDER BY g, v NULLS LAST;
SELECT g, v, first_value(v) OVER w, last_value(v) OVER w FROM frm WINDOW w AS (ORDER BY g ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE CURRENT ROW) ORDER BY g, v NULLS LAST;
-- lag and lead ignore the frame entirely
SELECT g, v, lag(v) OVER w, lead(v) OVER w FROM frm WINDOW w AS (ORDER BY g, v ROWS BETWEEN CURRENT ROW AND CURRENT ROW) ORDER BY g, v NULLS LAST;

-- RANGE offsets over temporal ordering columns use interval arithmetic
CREATE TABLE frm_ts (t timestamp, v int4);
INSERT INTO frm_ts VALUES ('2020-01-01 00:00:00', 1), ('2020-01-01 00:30:00', 2), ('2020-01-01 02:00:00', 4), ('2020-01-02 00:00:00', 8);
SELECT t, sum(v) OVER (ORDER BY t RANGE BETWEEN INTERVAL '1 hour' PRECEDING AND CURRENT ROW) FROM frm_ts ORDER BY t;
SELECT t, sum(v) OVER (ORDER BY t RANGE BETWEEN INTERVAL '1 hour' PRECEDING AND INTERVAL '1 hour' FOLLOWING) FROM frm_ts ORDER BY t;
SELECT t, sum(v) OVER (ORDER BY t DESC RANGE BETWEEN INTERVAL '1 hour' PRECEDING AND INTERVAL '1 hour' FOLLOWING) FROM frm_ts ORDER BY t;
SELECT t, count(*) OVER (ORDER BY t RANGE BETWEEN INTERVAL '1 day' PRECEDING AND UNBOUNDED FOLLOWING) FROM frm_ts ORDER BY t;

CREATE TABLE frm_d (d date, v int4);
INSERT INTO frm_d VALUES ('2020-01-01', 1), ('2020-01-02', 2), ('2020-01-05', 4);
SELECT d, sum(v) OVER (ORDER BY d RANGE BETWEEN INTERVAL '1 day' PRECEDING AND INTERVAL '1 day' FOLLOWING) FROM frm_d ORDER BY d;

CREATE TABLE frm_n (n numeric, v int4);
INSERT INTO frm_n VALUES (1.5, 1), (2.0, 2), (10.25, 4);
SELECT n, sum(v) OVER (ORDER BY n RANGE BETWEEN 0.5 PRECEDING AND 0.5 FOLLOWING) FROM frm_n ORDER BY n;
SELECT n, sum(v) OVER (ORDER BY n RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm_n ORDER BY n;

-- RANGE with NULL ordering values: the NULL peer group is its own frame
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN 5 PRECEDING AND 5 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN UNBOUNDED PRECEDING AND 5 FOLLOWING) FROM frm ORDER BY v NULLS LAST;
SELECT v, count(*) OVER (ORDER BY v NULLS FIRST RANGE BETWEEN 5 PRECEDING AND UNBOUNDED FOLLOWING) FROM frm ORDER BY v NULLS LAST;

-- an offset far past either end of the partition saturates, exactly as
-- PostgreSQL's in_range support functions clamp, rather than overflowing
SELECT g, count(*) OVER (ORDER BY g ROWS BETWEEN 9223372036854775807 PRECEDING AND 9223372036854775807 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, count(*) OVER (ORDER BY g GROUPS BETWEEN 9223372036854775807 PRECEDING AND 9223372036854775807 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, count(*) OVER (ORDER BY g ROWS BETWEEN 9223372036854775807 FOLLOWING AND 9223372036854775807 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, count(*) OVER (ORDER BY g GROUPS BETWEEN 9223372036854775807 PRECEDING AND 9223372036854775807 PRECEDING) FROM frm ORDER BY g, v NULLS LAST;
SELECT v, sum(v) OVER (ORDER BY v RANGE BETWEEN 2147483647 PRECEDING AND 2147483647 FOLLOWING) FROM frm ORDER BY v NULLS LAST;

-- error parity: same SQLSTATE on both sides
SELECT sum(v) OVER (ORDER BY g ROWS BETWEEN 1 FOLLOWING AND 1 PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS BETWEEN UNBOUNDED FOLLOWING AND CURRENT ROW) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS BETWEEN CURRENT ROW AND UNBOUNDED PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS BETWEEN CURRENT ROW AND 1 PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS -1 PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g GROUPS -1 PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS NULL PRECEDING) FROM frm;
SELECT sum(v) OVER (RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g, v RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY v RANGE BETWEEN -1 PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY v RANGE BETWEEN 1.5 PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT t, sum(v) OVER (ORDER BY t RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm_ts;

-- GROUPS counts peer groups, which only an ORDER BY defines, so PostgreSQL
-- requires one whatever the bounds are — unlike RANGE, which needs one only for
-- an offset bound.
SELECT sum(v) OVER (PARTITION BY g GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (GROUPS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM frm;
SELECT sum(v) OVER (GROUPS CURRENT ROW) FROM frm;
SELECT sum(v) OVER (PARTITION BY g GROUPS UNBOUNDED PRECEDING) FROM frm;
SELECT sum(v) OVER (w1 GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm WINDOW w1 AS (PARTITION BY g);
SELECT g, sum(v) OVER (RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;

-- a ROWS/GROUPS offset is a bigint count: a non-count type is 42804 and one that
-- reads the row is 42P10, both reported before any row is folded
SELECT sum(v) OVER (ORDER BY g ROWS INTERVAL '1 day' PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g GROUPS INTERVAL '1 day' PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS true PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g ROWS g PRECEDING) FROM frm;
SELECT sum(v) OVER (ORDER BY g RANGE BETWEEN g PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g GROUPS g PRECEDING) FROM frm;

-- an `unknown` literal RANGE offset adopts the type the ordering column's
-- in_range support function declares
SELECT g, sum(v) OVER (ORDER BY g RANGE BETWEEN '1' PRECEDING AND '1' FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, sum(v) OVER (ORDER BY g::int8 RANGE BETWEEN '1' PRECEDING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, sum(v) OVER (ORDER BY g::int2 RANGE BETWEEN '1' PRECEDING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT g, sum(v) OVER (ORDER BY g::numeric RANGE BETWEEN '1' PRECEDING AND 1 FOLLOWING) FROM frm ORDER BY g, v NULLS LAST;
SELECT sum(v) OVER (ORDER BY g RANGE BETWEEN 'x' PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g::int2 RANGE BETWEEN 'x' PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g::float8 RANGE BETWEEN 'x' PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g::numeric RANGE BETWEEN 'x' PRECEDING AND 1 FOLLOWING) FROM frm;
SELECT sum(v) OVER (ORDER BY g RANGE BETWEEN NULL PRECEDING AND 1 FOLLOWING) FROM frm;

-- a NaN or negative RANGE offset is rejected where PostgreSQL's in_range sees
-- it: per row, and never for a row whose ordering value is NULL
CREATE TABLE frm_fl (v float8);
INSERT INTO frm_fl VALUES (1), (2), ('NaN'), ('Infinity'), ('-Infinity'), (NULL);
CREATE TABLE frm_nm (v numeric);
INSERT INTO frm_nm VALUES (1.0), (2.0), ('NaN'), (NULL);
CREATE TABLE frm_empty (v float8);
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN 'NaN'::float8 PRECEDING AND 1 FOLLOWING) FROM frm_fl;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN CURRENT ROW AND 'NaN'::float8 FOLLOWING) FROM frm_fl;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN 'NaN'::numeric PRECEDING AND 1 FOLLOWING) FROM frm_nm;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN CURRENT ROW AND 'NaN'::numeric FOLLOWING) FROM frm_nm;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN -1 PRECEDING AND 1 FOLLOWING) FROM frm_empty;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN 'NaN'::float8 PRECEDING AND 1 FOLLOWING) FROM frm_empty;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN -1 PRECEDING AND 1 FOLLOWING) FROM (SELECT NULL::float8 v) q;
SELECT count(*) OVER (ORDER BY v RANGE BETWEEN 'NaN'::float8 PRECEDING AND 1 FOLLOWING) FROM (SELECT 'NaN'::float8 v) q;

-- a NaN ordering value has no arithmetic neighbourhood: its frame is exactly its
-- own peer run, and it is in no other row's frame
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN UNBOUNDED PRECEDING AND 1 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN 1 PRECEDING AND UNBOUNDED FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, count(*) OVER (ORDER BY v RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM frm_nm ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN UNBOUNDED PRECEDING AND 1 FOLLOWING) FROM frm_nm ORDER BY v NULLS LAST;

-- +inf infinitely precedes +inf and -inf infinitely follows -inf, so an infinite
-- offset against one admits every finite and infinite value — but not NaN
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN 'Infinity'::float8 PRECEDING AND 1 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN CURRENT ROW AND 'Infinity'::float8 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN 'Infinity'::float8 PRECEDING AND 'Infinity'::float8 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v DESC RANGE BETWEEN 'Infinity'::float8 PRECEDING AND 1 FOLLOWING) FROM frm_fl ORDER BY v DESC NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN 'Infinity'::float8 PRECEDING AND CURRENT ROW) FROM frm_fl ORDER BY v NULLS LAST;
SELECT v, array_agg(v::text) OVER (ORDER BY v RANGE BETWEEN 1 PRECEDING AND 'Infinity'::float8 FOLLOWING) FROM frm_fl ORDER BY v NULLS LAST;
