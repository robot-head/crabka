-- P5/S6 utility commands: ANALYZE, CLUSTER, REINDEX, CHECKPOINT, ALTER SYSTEM,
-- DISCARD targets, SET CONSTRAINTS, SET SESSION AUTHORIZATION, and EXPLAIN.
CREATE TABLE ut_t (id int4, s text);
INSERT INTO ut_t VALUES (1, 'a'), (2, 'b');

CHECKPOINT;
ANALYZE;
ANALYZE ut_t;
ANALYZE ut_t (id);
ANALYZE VERBOSE ut_t;
ANALYZE (VERBOSE false) ut_t;
CLUSTER;
REINDEX TABLE ut_t;
REINDEX SCHEMA public;
REINDEX (VERBOSE false) TABLE ut_t;

DISCARD PLANS;
DISCARD SEQUENCES;
DISCARD TEMP;
DISCARD TEMPORARY;
DISCARD ALL;

SET CONSTRAINTS ALL DEFERRED;
SET CONSTRAINTS ALL IMMEDIATE;
BEGIN;
SET CONSTRAINTS ALL DEFERRED;
SET CONSTRAINTS ALL IMMEDIATE;
COMMIT;

SET SESSION AUTHORIZATION DEFAULT;
RESET SESSION AUTHORIZATION;

ALTER SYSTEM SET wal_level = 'replica';
ALTER SYSTEM RESET wal_level;
ALTER SYSTEM SET no_such_parameter_at_all = 1;

-- EXPLAIN (COSTS OFF) over the statement shapes the interpreter executes.
EXPLAIN (COSTS OFF) SELECT * FROM ut_t;
EXPLAIN (COSTS OFF) SELECT id FROM ut_t WHERE id = 1;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t WHERE s = 'a';
EXPLAIN (COSTS OFF) SELECT * FROM ut_t WHERE id > 1 AND s < 'b';
EXPLAIN (COSTS OFF) SELECT * FROM ut_t WHERE id IS NULL;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t WHERE id + 1 = 2;
EXPLAIN (COSTS OFF) SELECT count(*) FROM ut_t;
EXPLAIN (COSTS OFF) SELECT count(*) FROM ut_t WHERE id = 1;
EXPLAIN (COSTS OFF) SELECT id, count(*) FROM ut_t GROUP BY id;
EXPLAIN (COSTS OFF) SELECT id, count(*) FROM ut_t GROUP BY id HAVING count(*) > 1;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t ORDER BY id;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t ORDER BY id DESC, s;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t LIMIT 1;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t LIMIT 1 OFFSET 1;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t x WHERE x.id = 1;
EXPLAIN (COSTS OFF) SELECT 1 + 1;
EXPLAIN (COSTS OFF) UPDATE ut_t SET s = 'z' WHERE id = 1;
EXPLAIN (COSTS OFF) DELETE FROM ut_t WHERE id = 1;
EXPLAIN (COSTS OFF) INSERT INTO ut_t VALUES (3, 'c');
EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF, BUFFERS OFF) SELECT 1;
EXPLAIN (COSTS OFF, FORMAT TEXT) SELECT * FROM ut_t;
EXPLAIN (COSTS OFF, VERBOSE FALSE) SELECT * FROM ut_t;
EXPLAIN (COSTS OFF) SELECT * FROM ut_t;
EXPLAIN (COSTS OFF, FORMAT NONSENSE) SELECT 1;
EXPLAIN (NO_SUCH_OPTION) SELECT 1;
SELECT id, s FROM ut_t ORDER BY id;

DROP TABLE ut_t;

-- Only DISCARD ALL is refused inside a transaction block; PostgreSQL runs the
-- other four there.
BEGIN;
DISCARD PLANS;
DISCARD SEQUENCES;
DISCARD TEMP;
DISCARD TEMPORARY;
DISCARD ALL;
ROLLBACK;
BEGIN;
DISCARD PLANS;
COMMIT;
