-- Set-operation completeness: ALL/DISTINCT spellings, precedence and
-- associativity, cross-branch type resolution, and the result-level tail.

CREATE TABLE q3so_l (a int4, b text);
CREATE TABLE q3so_r (a int4, b text);
INSERT INTO q3so_l VALUES (1,'x'),(2,'y'),(2,'y'),(3,'z'),(NULL,'n');
INSERT INTO q3so_r VALUES (2,'y'),(3,'q'),(4,'w'),(NULL,'n');

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l UNION ALL SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l UNION DISTINCT SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l INTERSECT SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l INTERSECT ALL SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l INTERSECT DISTINCT SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l EXCEPT SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l EXCEPT ALL SELECT a FROM q3so_r ORDER BY a;

SELECT a FROM q3so_l EXCEPT DISTINCT SELECT a FROM q3so_r ORDER BY a;

-- NULL is "not distinct from" NULL for duplicate elimination.
SELECT a FROM q3so_l WHERE a IS NULL UNION SELECT a FROM q3so_r WHERE a IS NULL;

SELECT a FROM q3so_l WHERE a IS NULL INTERSECT SELECT a FROM q3so_r WHERE a IS NULL;

SELECT a FROM q3so_l WHERE a IS NULL EXCEPT SELECT a FROM q3so_r WHERE a IS NULL;

-- Whole rows, not just single columns.
SELECT a, b FROM q3so_l UNION SELECT a, b FROM q3so_r ORDER BY a, b;

SELECT a, b FROM q3so_l EXCEPT SELECT a, b FROM q3so_r ORDER BY a, b;

SELECT a, b FROM q3so_l INTERSECT ALL SELECT a, b FROM q3so_r ORDER BY a, b;

-- Precedence: INTERSECT binds tighter than UNION and EXCEPT.
SELECT 1 UNION SELECT 2 INTERSECT SELECT 2 ORDER BY 1;

SELECT 1 UNION ALL SELECT 2 INTERSECT SELECT 3 ORDER BY 1;

(SELECT 1 UNION SELECT 2) INTERSECT SELECT 2 ORDER BY 1;

SELECT 1 EXCEPT SELECT 2 INTERSECT SELECT 1 ORDER BY 1;

SELECT 2 EXCEPT SELECT 2 INTERSECT SELECT 2 ORDER BY 1;

-- Associativity: UNION and EXCEPT are left-associative.
SELECT a FROM q3so_l EXCEPT SELECT a FROM q3so_r UNION SELECT 9 ORDER BY 1;

SELECT 1 UNION SELECT 2 EXCEPT SELECT 1 ORDER BY 1;

SELECT 1 EXCEPT SELECT 1 UNION SELECT 2 ORDER BY 1;

SELECT 1 EXCEPT (SELECT 1 UNION SELECT 2) ORDER BY 1;

SELECT 1 UNION (SELECT 2 EXCEPT SELECT 1) ORDER BY 1;

SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION ALL SELECT 3 ORDER BY 1;

-- Cross-branch type resolution: the numeric tower and the `unknown` literal rule.
SELECT 1 UNION SELECT 2::int8 ORDER BY 1;

SELECT 1::int2 UNION SELECT 2::int4 ORDER BY 1;

SELECT 1 UNION SELECT 2.5 ORDER BY 1;

SELECT 1::int4 UNION SELECT 2::float8 ORDER BY 1;

SELECT 1 UNION SELECT NULL ORDER BY 1;

SELECT NULL UNION SELECT 1 ORDER BY 1;

SELECT NULL UNION SELECT NULL;

SELECT 'a' UNION SELECT 'b' ORDER BY 1;

SELECT 'a'::text UNION SELECT 'b' ORDER BY 1;

SELECT 1 UNION SELECT '2' ORDER BY 1;

SELECT true UNION SELECT false ORDER BY 1;

-- Output column names come from the leftmost branch.
SELECT a AS leftname FROM q3so_l UNION SELECT a AS rightname FROM q3so_r ORDER BY leftname;

-- ORDER BY / LIMIT / OFFSET apply to the whole set expression.
SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY a DESC;

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY 1 LIMIT 2;

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY 1 OFFSET 2;

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY a NULLS FIRST LIMIT 3;

SELECT a FROM q3so_l UNION ALL SELECT a FROM q3so_r ORDER BY a ASC LIMIT 4 OFFSET 1;

SELECT a, b FROM q3so_l UNION SELECT a, b FROM q3so_r ORDER BY 2, 1;

-- A parenthesised branch may carry its own ORDER BY / LIMIT.
(SELECT a FROM q3so_l ORDER BY a LIMIT 2) UNION ALL (SELECT a FROM q3so_r ORDER BY a LIMIT 1)
ORDER BY 1;

(SELECT a FROM q3so_l ORDER BY a DESC LIMIT 1) UNION (SELECT a FROM q3so_r ORDER BY a LIMIT 1)
ORDER BY 1;

-- VALUES as a branch, and set operations under a CTE / derived table.
VALUES (1), (2) UNION SELECT 3 ORDER BY 1;

SELECT a FROM q3so_l UNION VALUES (7) ORDER BY 1;

WITH u AS (SELECT a FROM q3so_l UNION SELECT a FROM q3so_r) SELECT count(*) FROM u;

SELECT count(*) FROM (SELECT a FROM q3so_l EXCEPT SELECT a FROM q3so_r) d;

SELECT * FROM (SELECT 1 UNION SELECT 2) d(x) ORDER BY x;

SELECT a FROM q3so_l WHERE a IN (SELECT a FROM q3so_r UNION SELECT 9) ORDER BY a;

SELECT EXISTS (SELECT 1 INTERSECT SELECT 1);

-- Aggregates over a set-operation result.
SELECT sum(a), count(*) FROM (SELECT a FROM q3so_l UNION ALL SELECT a FROM q3so_r) d;

-- Errors.
SELECT a FROM q3so_l UNION SELECT a, b FROM q3so_r;

SELECT a FROM q3so_l INTERSECT SELECT b FROM q3so_r;

SELECT 1 UNION SELECT 'x'::text;

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY 5;

SELECT a FROM q3so_l UNION SELECT a FROM q3so_r ORDER BY b;

DROP TABLE q3so_l;
DROP TABLE q3so_r;
