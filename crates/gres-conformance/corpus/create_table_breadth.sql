-- `bpchar` is PostgreSQL's own name for the blank-padded character type and is
-- accepted as a type name, carrying no implicit (1). `public` is not a keyword
-- in PostgreSQL at all, so it works as a column label.
SELECT length('ab'::bpchar), 'ab'::bpchar, upper('ab'::bpchar);
CREATE TABLE bpc (c bpchar);
INSERT INTO bpc VALUES ('xy');
SELECT c FROM bpc;
DROP TABLE bpc;
SELECT 1 AS public;
