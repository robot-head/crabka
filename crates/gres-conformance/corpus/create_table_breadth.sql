-- D4/D7: CREATE TABLE breadth, diffed against PostgreSQL 18.4.
-- IF NOT EXISTS, `(LIKE source …)`, empty column lists, named table
-- constraints, GENERATED … AS IDENTITY, GENERATED ALWAYS AS (…) STORED,
-- CREATE INDEX options, and COMMENT ON.
-- The harness runs every statement over ONE connection, so state accumulates.
CREATE TABLE ctb_base (id int4 PRIMARY KEY, v text NOT NULL, w text);
INSERT INTO ctb_base VALUES (1, 'a', 'b');
SELECT id, v, w FROM ctb_base;
-- IF NOT EXISTS makes a duplicate name a no-op instead of 42P07.
CREATE TABLE ctb_base (id int4);
CREATE TABLE IF NOT EXISTS ctb_base (id int4);
SELECT id, v, w FROM ctb_base;
-- LIKE copies the column list; NOT NULL rides along, DEFAULT/indexes do not.
CREATE TABLE ctb_like (LIKE ctb_base);
INSERT INTO ctb_like VALUES (1, 'x', NULL);
INSERT INTO ctb_like VALUES (1, 'y', NULL);
INSERT INTO ctb_like VALUES (2, NULL, NULL);
SELECT id, v, w FROM ctb_like ORDER BY id, v;
CREATE TABLE ctb_like_all (LIKE ctb_base INCLUDING ALL);
INSERT INTO ctb_like_all VALUES (1, 'x', NULL);
INSERT INTO ctb_like_all VALUES (1, 'y', NULL);
SELECT id, v, w FROM ctb_like_all ORDER BY id;
CREATE TABLE ctb_like_missing (LIKE ctb_nope);
-- LIKE with explicit columns added after it.
CREATE TABLE ctb_like_extra (LIKE ctb_base, extra int4 DEFAULT 9);
INSERT INTO ctb_like_extra (id, v) VALUES (1, 'q');
SELECT id, v, w, extra FROM ctb_like_extra;
-- An empty column list is legal.
CREATE TABLE ctb_empty ();
SELECT count(*) FROM ctb_empty;
-- Named table constraints and default constraint names.
